export function summaryExportCopy(locale: SummaryLocale): SummaryExportCopy {
  const values = translations[locale];
  if (values.length !== keys.length) throw new Error(`Incomplete export translations: ${locale}`);
  return {
    ...Object.fromEntries(keys.map((key, index) => [key, values[index]!])),
    ...pairedRecoveryCopy[locale],
    ...evidenceCopy[locale],
  } as SummaryExportCopy;
}
