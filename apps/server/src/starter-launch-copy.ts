export type LaunchCopyKey = keyof typeof rows;
export function launchCopy(locale: SupportedLocale, key: LaunchCopyKey): string {
  const index = locales.indexOf(locale);
  if (index < 0) throw new Error(`Unsupported launch collection locale: ${locale}`);
  const value = rows[key][index];
  if (!value?.trim()) throw new Error(`Missing launch collection copy: ${locale}/${key}`);
  return value;
}
