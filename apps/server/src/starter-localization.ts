function indexFor(locale: SupportedLocale) {
  const index = starterTranslationLocales.indexOf(
    locale as (typeof starterTranslationLocales)[number],
  );
  if (index < 0) throw new Error(`Unsupported starter content locale: ${locale}`);
  return index as 0 | 1 | 2 | 3 | 4 | 5 | 6 | 7 | 8;
}

export function localizedStarter(
  source: QuizDraft,
  id: StarterId,
  locale: SupportedLocale,
): QuizDraft {
  const result = structuredClone(source);
  if (locale === "en-CA") return result;
  const column = indexFor(locale);
  const values = content[id][column].split("|");
  let position = 0;
  const text = (value: string) => {
    if (!value || !/\p{L}/u.test(value)) return value;
    if (shared[value]) return shared[value][column];
    const translated = values[position++];
    if (!translated?.trim()) throw new Error(`Missing starter copy: ${locale}/${id}/${position}`);
    return translated;
  };
  result.title = text(source.title);
  result.description = descriptions[source.description]?.[column] ?? "";
  if (!result.description) throw new Error(`Missing starter description: ${id}/${locale}`);
  for (const question of result.questions) {
    question.prompt = text(question.prompt);
    question.explanation = text(question.explanation);
    if ("choices" in question)
      for (const choice of question.choices) {
        choice.label = text(choice.label);
        if (choice.feedback) choice.feedback = text(choice.feedback);
      }
    if (question.type === "rating") {
      question.minLabel = text(question.minLabel);
      question.maxLabel = text(question.maxLabel);
    }
    if (question.type === "numeric" && question.unit) question.unit = text(question.unit);
  }
  if (position !== values.length)
    throw new Error(`Extra starter copy: ${locale}/${id}: ${position}/${values.length}`);
  return result;
}

export function localizedStarterDescription(
  source: string,
  draft: QuizDraft,
  locale: SupportedLocale,
) {
  if (locale === "en-CA") return source;
  const column = indexFor(locale);
  if (descriptions[source]) return descriptions[source][column];
  if (source.endsWith(" Follow with a labeled reflection scale."))
    return `${draft.questions[0]!.prompt} ${reflectionScale[column]}`;
  return shared[source]?.[column] ?? draft.questions[0]!.explanation;
}

