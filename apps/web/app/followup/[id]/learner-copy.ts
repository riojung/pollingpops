export const learnerCopyKeys = Object.keys(rows) as Array<keyof typeof rows>;
export function learnerCopy(locale: SupportedLocale) {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  return (key: keyof typeof rows, values: Record<string, string | number> = {}) => {
    const template: string = column < 0 ? key : rows[key][column]!;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
  };
}
