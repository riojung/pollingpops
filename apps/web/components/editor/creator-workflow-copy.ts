export function creatorWorkflowCopy(locale: SupportedLocale): Copy {
  const values = translated[locale];
  const copy = Object.fromEntries(
    Object.entries(english).map(([key, value], index) => [key, values?.[index] ?? value]),
  ) as Copy;
  const otherStarts: Record<SupportedLocale, string> = {
    "en-CA": "Other starting points",
    "fr-FR": "Autres points de départ",
    "de-DE": "Weitere Ausgangspunkte",
    "es-ES": "Otras formas de empezar",
    "it-IT": "Altri punti di partenza",
    "pt-PT": "Outros pontos de partida",
    "ja-JP": "その他の始め方",
    "ko-KR": "다른 시작 방법",
    "zh-CN": "其他开始方式",
    "zh-TW": "其他開始方式",
  };
  return { ...copy, otherStartingPoints: otherStarts[locale] ?? english.otherStartingPoints };
}
