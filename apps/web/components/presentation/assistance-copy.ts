export type AssistanceCopyKey = keyof typeof messages | "Outline to slides";
export const assistanceCopyKeys: readonly AssistanceCopyKey[] = [
  "Outline to slides",
  ...(Object.keys(messages) as (keyof typeof messages)[]),
];

export function assistanceCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  return (key: AssistanceCopyKey, values: Record<string, string | number> = {}): string => {
    const message =
      key === "Outline to slides"
        ? presentationCommandCopy(locale).outlineToSlides
        : column < 0
          ? key
          : messages[key][column]!;
    return message.replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token));
  };
}

