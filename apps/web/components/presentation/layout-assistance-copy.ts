type LocalKey = keyof typeof messages;
export type LayoutAssistanceCopyKey =
  LocalKey | (typeof controlKeys)[number] | (typeof assistanceKeys)[number];
export const layoutAssistanceCopyKeys: readonly LayoutAssistanceCopyKey[] = [
  ...controlKeys,
  ...assistanceKeys,
  ...(Object.keys(messages) as LocalKey[]),
];
export function isLayoutAssistanceCopyKey(message: string): message is LayoutAssistanceCopyKey {
  return (
    Object.hasOwn(messages, message) ||
    [...controlKeys, ...assistanceKeys].some((key) => key === message)
  );
}
export function layoutAssistanceCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  const sharedCopy = nativeControlsCopy(locale);
  const sharedAssistanceCopy = assistanceCopy(locale);
  return (key: LayoutAssistanceCopyKey, values: Record<string, string | number> = {}): string => {
    const message = Object.hasOwn(messages, key)
      ? column < 0
        ? key
        : messages[key as LocalKey][column]!
      : key === "Close"
        ? sharedAssistanceCopy(key, values)
        : sharedCopy(key as (typeof controlKeys)[number], values);
    return message.replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token));
  };
}

/** Call only for known generator descriptors/reasons and system error strings. */
export function layoutAssistanceSystemMessage(locale: SupportedLocale, message: string) {
  return isLayoutAssistanceCopyKey(message) ? layoutAssistanceCopy(locale)(message) : message;
}
