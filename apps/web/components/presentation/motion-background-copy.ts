export type MotionBackgroundCopyKey = keyof typeof messages;
export const motionBackgroundCopyKeys = Object.keys(messages) as MotionBackgroundCopyKey[];

export function motionBackgroundCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  return (key: MotionBackgroundCopyKey): string => (column < 0 ? key : messages[key][column]!);
}
