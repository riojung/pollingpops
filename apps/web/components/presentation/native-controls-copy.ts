const messages = { ...labels, ...guidance };
export type NativeControlsCopyKey = keyof typeof messages;
export const nativeControlsCopyKeys = Object.keys(messages) as NativeControlsCopyKey[];
export function nativeControlsCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  return (key: NativeControlsCopyKey, values: Record<string, string | number> = {}) => {
    const message = column < 0 ? key : (messages[key][column] ?? key);
    return message.replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token));
  };
}

/** Explicit node fields distinguish an authored English label from an identical generated fallback. */
export function nativeControlNodeLabel(locale: SupportedLocale, node: PresentationSceneNode) {
  const copy = nativeControlsCopy(locale);
  let authored = "";
  let key: NativeControlsCopyKey = "Connection";
  if (node.type === "text") {
    if (node.role === "title") key = "Slide title";
    else {
      authored = node.text.trim().slice(0, 40);
      key = "Body text";
    }
  } else if (node.type === "image") {
    authored = node.altText?.trim() ?? "";
    key = "Image";
  } else if (node.type === "shape") {
    authored = node.label.trim();
    if (!authored)
      return {
        text: copy("{shape} shape", {
          shape: copy(node.shape.replaceAll("_", " ") as NativeControlsCopyKey),
        }),
        language: locale,
      };
  } else if (node.type === "table") {
    authored = node.caption.trim();
    key = "Data table";
  } else if (node.type === "chart") {
    authored = node.title.trim();
    if (!authored)
      return { text: copy("{type} chart", { type: copy(node.chartType) }), language: locale };
  } else {
    authored = node.label.trim();
    key = {
      reveal: "Reveal panel",
      link: "External link",
      hotspot: "Image hotspot",
      dialog: "Detail dialog",
      navigation: "Slide link",
      connector: "Connection",
    }[node.type] as NativeControlsCopyKey;
  }
  return {
    text: authored || copy(key),
    language: authored ? (node.type === "text" ? (node.lang ?? "") : "") : locale,
  };
}
