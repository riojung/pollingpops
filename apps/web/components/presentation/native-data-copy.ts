/** Adapt the shared library's unchanged English contract at display time, never in draft state.
 * Only exact source messages and bounded numeric source templates are accepted. Unknown
 * diagnostics (which may contain arbitrary source text) remain intact and explicitly English.
 */
export function nativeDataFeedback(locale: SupportedLocale, source: string) {
  const copy = nativeDataCopy(locale);
  const withRecovery = source.endsWith(recoverySuffix);
  const message = withRecovery ? source.slice(0, -recoverySuffix.length) : source;
  let text: string | undefined;
  if (finiteFeedback.has(message as NativeDataCopyKey)) {
    text = copy(message as NativeDataCopyKey);
  } else {
    const numeric =
      /^Row ([1-9]\d?), series ([1-4]): use a finite number between −1 trillion and 1 trillion\. Formulas and blank values are unsupported\.$/.exec(
        message,
      );
    if (numeric && Number(numeric[1]) <= 20) {
      text = copy(numberError, { row: numeric[1]!, series: numeric[2]! });
    }
    const bound =
      /^(Too big: expected string to have <=)(80|120|160|300|800)( characters)$|^(Too big: expected array to have <=)(4|6|20)( items)$|^(Too small: expected array to have >=)(1)( items)$/.exec(
        message,
      );
    if (bound) {
      const prefix = bound[1] ?? bound[4] ?? bound[7]!;
      const limit = bound[2] ?? bound[5] ?? bound[8]!;
      const suffix = bound[3] ?? bound[6] ?? bound[9]!;
      text = copy(`${prefix}{limit}${suffix}` as NativeDataCopyKey, { limit });
    }
  }
  if (text === undefined) return { text: source, language: "en-CA" as const };
  return { text: withRecovery ? `${text} ${copy(recovery)}` : text, language: locale };
}
