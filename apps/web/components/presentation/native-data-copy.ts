type LocalKey = keyof typeof messages;
export type NativeDataCopyKey = LocalKey | keyof typeof sharedLabels;
export const nativeDataCopyKeys: readonly NativeDataCopyKey[] = [
  ...(Object.keys(sharedLabels) as (keyof typeof sharedLabels)[]),
  ...(Object.keys(messages) as LocalKey[]),
];

function isLocalKey(key: NativeDataCopyKey): key is LocalKey {
  return Object.hasOwn(messages, key);
}

export function nativeDataCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  const sharedCopy = nativeEditorCopy(locale);
  return (key: NativeDataCopyKey, values: Record<string, string | number> = {}): string => {
    if (!isLocalKey(key)) return column < 0 ? key : sharedCopy(sharedLabels[key]);
    const message = column < 0 ? key : messages[key][column]!;
    return message.replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token));
  };
}

