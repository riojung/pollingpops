const messages = { ...labels, ...guidance };
type LocalKey = keyof typeof messages;
export type NativeEditorCopyKey = LocalKey | (typeof sharedKeys)[number];
export const nativeEditorCopyKeys: readonly NativeEditorCopyKey[] = [
  ...sharedKeys,
  ...(Object.keys(messages) as LocalKey[]),
];

function isLocalKey(key: NativeEditorCopyKey): key is LocalKey {
  return Object.hasOwn(messages, key);
}

export function nativeEditorCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  const sharedCopy = nativeControlsCopy(locale);
  return (key: NativeEditorCopyKey, values: Record<string, string | number> = {}): string => {
    if (!isLocalKey(key)) return sharedCopy(key, values);
    const message = column < 0 ? key : messages[key][column]!;
    return message.replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token));
  };
}
