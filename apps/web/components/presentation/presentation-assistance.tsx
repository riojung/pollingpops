"use client";

import { useEffect, useRef, useState, type FormEvent, type KeyboardEvent } from "react";
import type { PresentationAssistanceProposal } from "@openround/contracts";
import { AUTH_CHANGE_EVENT, humanError } from "../../lib/api";
import {
  createPresentationAssistance,
  fetchPresentationAssistanceStatus,
  type AssistanceState,
  type PresentationAssistanceStatus,
} from "../../lib/presentation-assistance-client";
import styles from "./presentation-assistance.module.css";

const focusable =
  'button:not([disabled]), input:not([disabled]), textarea:not([disabled]), select:not([disabled]), [tabindex="0"]';
type Controller = ReturnType<typeof createPresentationAssistance>;

interface Props {
  presentationId: string;
  actorKey: string;
  canEdit: boolean;
  open: boolean;
  expectedRevision: number;
  afterBlockId: string | null;
  onInserted: (ids: string[]) => Promise<void>;
  onReloadDraft: () => Promise<void>;
  onClose: () => void;
  onResumeRequired: () => void;
  onPendingChange: (pending: boolean) => void;
}

export function AssistanceProposalReview({
  proposal,
  selectedSlideIds,
  reviewed,
  disabled,
  onSelect,
  onReview,
}: {
  proposal: PresentationAssistanceProposal;
  selectedSlideIds: string[];
  reviewed: boolean;
  disabled: boolean;
  onSelect: (id: string) => void;
  onReview: (value: boolean) => void;
}) {
  return (
    <section className={styles.proposal} aria-label="Review proposed slides">
      <h3>Review proposed slides</h3>
      <p className={styles.warning}>
        {proposal.reviewWarning} Exact source excerpts help your review; citations do not verify the
        generated claims.
      </p>
      <p className={styles.help}>
        Generated by {proposal.provider} / {proposal.model}. Only selected slides will be inserted.
        No questions, media or speaker notes are generated.
      </p>
      <fieldset disabled={disabled} className={styles.slides}>
        <legend>Slides to insert</legend>
        {proposal.slides.map((slide, index) => (
          <article className={styles.slide} key={slide.id}>
            <label className={styles.check}>
              <input
                type="checkbox"
                checked={selectedSlideIds.includes(slide.id)}
                onChange={() => onSelect(slide.id)}
              />
              <span>
                Include slide {index + 1}: {slide.title}
              </span>
            </label>
            <h4>{slide.title}</h4>
            <p className={styles.slideBody}>{slide.body}</p>
            <h5>Exact outline excerpts</h5>
            <ul>
              {slide.citations.map((citation, citationIndex) => (
                <li key={`${citation.locator}:${citationIndex}`}>
                  <strong>{citation.locator}</strong>
                  <blockquote>{citation.excerpt}</blockquote>
                </li>
              ))}
            </ul>
          </article>
        ))}
        <label className={styles.check}>
          <input
            type="checkbox"
            checked={reviewed}
            onChange={(event) => onReview(event.target.checked)}
          />
          <span>
            I reviewed the selected slide text and exact excerpts, including any unsupported claims.
          </span>
        </label>
      </fieldset>
    </section>
  );
}

export function PresentationAssistance(props: Props) {
  const { presentationId, actorKey, canEdit, open, expectedRevision, afterBlockId } = props;
  const storageKey = `presentation-assistance:${actorKey}:${presentationId}`;
  const [state, setState] = useState<AssistanceState>({
    job: null,
    selectedSlideIds: [],
    reviewed: false,
    busy: null,
    pendingInsert: false,
    error: "",
    message: "",
  });
  const [status, setStatus] = useState<PresentationAssistanceStatus | null>(null);
  const [availabilityError, setAvailabilityError] = useState("");
  const [availabilityAttempt, setAvailabilityAttempt] = useState(0);
  const [sourceName, setSourceName] = useState("");
  const [outline, setOutline] = useState("");
  const [slideCount, setSlideCount] = useState(3);
  const [recovered, setRecovered] = useState(false);
  const [formError, setFormError] = useState("");
  const [authInvalid, setAuthInvalid] = useState(false);
  const controller = useRef<Controller | null>(null);
  const dialog = useRef<HTMLDivElement>(null);
  const current = useRef(props);
  current.current = props;
  const allowed = useRef(canEdit);
  allowed.current = canEdit && !authInvalid;

  useEffect(() => {
    const session = createPresentationAssistance({
      presentationId,
      canEdit: () => allowed.current && current.current.actorKey === actorKey,
      persist: (value) => {
        if (value) window.sessionStorage.setItem(storageKey, JSON.stringify(value));
        else window.sessionStorage.removeItem(storageKey);
      },
      onState: (next) => {
        setState(next);
        current.current.onPendingChange(next.pendingInsert);
      },
      onInserted: async (ids) => {
        await current.current.onInserted(ids);
        current.current.onClose();
      },
    });
    controller.current = session;
    try {
      const saved = window.sessionStorage.getItem(storageKey);
      if (saved) {
        session.restore(JSON.parse(saved));
        setRecovered(true);
        if (session.state().pendingInsert) current.current.onResumeRequired();
        if (canEdit) void session.refresh();
      }
    } catch (error) {
      setFormError(humanError(error));
    }
    const authChanged = () => {
      allowed.current = false;
      session.cancel();
      setAuthInvalid(true);
      setOutline("");
      setSourceName("");
      setState({
        ...session.state(),
        job: null,
        selectedSlideIds: [],
        reviewed: false,
        busy: null,
        error: "Your sign-in changed. Reload the editor before using AI assistance.",
        message: "",
      });
      try {
        window.sessionStorage.removeItem(storageKey);
      } catch {
        /* Restricted storage may already be unavailable. */
      }
    };
    window.addEventListener(AUTH_CHANGE_EVENT, authChanged);
    return () => {
      session.cancel();
      window.removeEventListener(AUTH_CHANGE_EVENT, authChanged);
    };
  }, [actorKey, presentationId, storageKey, canEdit]);

  useEffect(() => {
    if (!open || !canEdit || authInvalid) return;
    const abort = new AbortController();
    setStatus(null);
    setAvailabilityError("");
    void fetchPresentationAssistanceStatus(presentationId, abort.signal)
      .then((value) => {
        if (!abort.signal.aborted) setStatus(value);
      })
      .catch((error) => {
        if (!abort.signal.aborted) setAvailabilityError(humanError(error));
      });
    return () => abort.abort();
  }, [open, canEdit, authInvalid, presentationId, availabilityAttempt]);

  useEffect(() => {
    if (!open) return;
    const previous = document.activeElement instanceof HTMLElement ? document.activeElement : null;
    (dialog.current?.querySelector<HTMLElement>(focusable) ?? dialog.current)?.focus();
    return () => previous?.focus();
  }, [open]);

  useEffect(() => {
    if (!open || state.busy || !["pending", "processing"].includes(state.job?.status ?? "")) return;
    const timer = window.setTimeout(() => void controller.current?.refresh(), 2_000);
    return () => window.clearTimeout(timer);
  }, [open, state.job, state.busy]);

  function keyDown(event: KeyboardEvent<HTMLDivElement>) {
    if (event.key === "Escape") {
      event.preventDefault();
      props.onClose();
      return;
    }
    if (event.key !== "Tab") return;
    const fields = [...event.currentTarget.querySelectorAll<HTMLElement>(focusable)].filter(
      (field) => field.offsetParent !== null,
    );
    const first = fields[0];
    const last = fields.at(-1);
    if (!first || !last) {
      event.preventDefault();
      event.currentTarget.focus();
    } else if (event.shiftKey && document.activeElement === first) {
      event.preventDefault();
      last.focus();
    } else if (!event.shiftKey && document.activeElement === last) {
      event.preventDefault();
      first.focus();
    }
  }
  async function generate(event: FormEvent) {
    event.preventDefault();
    setFormError("");
    if (!status?.enabled || status.remaining === 0 || status.active >= status.maxActiveJobs) return;
    try {
      await controller.current?.generate({ sourceName, outline, slideCount });
      setAvailabilityAttempt((value) => value + 1);
    } catch (error) {
      setFormError(humanError(error));
    }
  }
  function startAgain() {
    try {
      if (controller.current?.reset()) {
        setRecovered(false);
        setFormError("");
      }
    } catch (error) {
      setFormError(humanError(error));
    }
  }
  async function insert() {
    try {
      await controller.current?.insert(expectedRevision, afterBlockId);
    } catch (error) {
      setFormError(humanError(error));
    }
  }
  async function reloadDraft() {
    try {
      setFormError("");
      await props.onReloadDraft();
    } catch (error) {
      setFormError(humanError(error));
    }
  }
  if (!open) return null;
  const disabled = Boolean(state.busy) || !canEdit || authInvalid;
  const unavailable =
    !status?.enabled || status.remaining === 0 || status.active >= status.maxActiveJobs;
  return (
    <div
      className={styles.backdrop}
      role="dialog"
      aria-modal="true"
      aria-labelledby="presentation-assistance-title"
      ref={dialog}
      tabIndex={-1}
      onKeyDown={keyDown}
      lang="en-CA"
    >
      <section className={styles.dialog}>
        <div className={styles.heading}>
          <div>
            <p className={styles.eyebrow}>Optional AI assistance</p>
            <h2 id="presentation-assistance-title">Outline to slides</h2>
          </div>
          <button type="button" onClick={props.onClose}>
            Close
          </button>
        </div>
        <p>
          Turn your outline into 3–8 editable text slides. Review the proposal, select slides, then
          insert them into this saved deck. Generation never publishes or changes your deck.
        </p>
        <p className={styles.help}>
          Only the named outline is sent to the operator-configured provider. Ordinary slide
          creation and editing remain available without AI.
        </p>
        <div className={styles.notice} role="status" aria-live="polite">
          {!canEdit ? (
            "Editor permission is required to generate or insert slides."
          ) : authInvalid ? (
            "Reload the editor after a sign-in change."
          ) : status ? (
            <>
              <p>
                {status.monthlyLimit === null
                  ? `${status.used} AI jobs used this month; operator-configured allowance.`
                  : `${status.used} of ${status.monthlyLimit} AI jobs used this month (${status.remaining} remaining).`}{" "}
                One new outline proposal uses one job.
              </p>
              {!status.enabled ? (
                <p>
                  AI assistance is disabled on this deployment. An operator can configure an
                  approved provider. Your outline has not been sent.
                </p>
              ) : status.remaining === 0 ? (
                <p>
                  Your monthly AI allowance is used. Continue editing manually or return when your
                  allowance resets.
                </p>
              ) : status.active >= status.maxActiveJobs ? (
                <p>
                  Two AI jobs are already active. Wait for a job to finish, then retry availability.
                </p>
              ) : null}
            </>
          ) : availabilityError ? null : (
            "Checking AI availability and allowance…"
          )}
        </div>
        {availabilityError ? <p role="alert">{availabilityError}</p> : null}
        {availabilityError || status ? (
          <button
            type="button"
            className={styles.secondary}
            disabled={disabled}
            onClick={() => setAvailabilityAttempt((value) => value + 1)}
          >
            Retry availability
          </button>
        ) : null}
        {formError || state.error ? (
          <p className={styles.error} role="alert">
            {formError || state.error}
          </p>
        ) : null}
        {state.message ? (
          <p className={styles.notice} role="status">
            {state.message}
          </p>
        ) : null}
        {!state.job && !recovered ? (
          <form onSubmit={(event) => void generate(event)} className={styles.form}>
            <fieldset disabled={disabled || unavailable}>
              <legend>Your outline</legend>
              <label>
                Outline name
                <input
                  required
                  maxLength={160}
                  value={sourceName}
                  onChange={(event) => {
                    controller.current?.reset();
                    setSourceName(event.target.value);
                  }}
                />
              </label>
              <label>
                Outline text
                <textarea
                  required
                  rows={8}
                  minLength={50}
                  maxLength={12_000}
                  value={outline}
                  onChange={(event) => {
                    controller.current?.reset();
                    setOutline(event.target.value);
                  }}
                />
              </label>
              <p className={styles.help}>
                {outline.length} / 12,000 characters. Include the facts you want covered. Each
                non-empty line becomes a source locator. Keep private information out unless you
                have permission to share it.
              </p>
              <label>
                Number of slides
                <select
                  value={slideCount}
                  onChange={(event) => {
                    controller.current?.reset();
                    setSlideCount(Number(event.target.value));
                  }}
                >
                  {[3, 4, 5, 6, 7, 8].map((count) => (
                    <option key={count} value={count}>
                      {count}
                    </option>
                  ))}
                </select>
              </label>
              <button type="submit">
                {state.busy === "generate" ? "Creating proposal…" : "Create slide proposal"}
              </button>
            </fieldset>
          </form>
        ) : null}
        {state.job ? (
          <p role="status">
            {state.job.status === "pending"
              ? "Proposal queued."
              : state.job.status === "processing"
                ? "Creating slides for review…"
                : state.job.status === "failed" || state.job.status === "expired"
                  ? `Proposal ${state.job.status}. ${state.job.error?.message ?? "Start another outline when ready."}`
                  : "Ready for review."}
          </p>
        ) : null}
        {state.job?.proposal ? (
          <>
            <AssistanceProposalReview
              proposal={state.job.proposal}
              selectedSlideIds={state.selectedSlideIds}
              reviewed={state.reviewed}
              disabled={disabled || state.pendingInsert}
              onSelect={(id) => controller.current?.select(id)}
              onReview={(value) => controller.current?.review(value)}
            />
            <button
              type="button"
              disabled={
                disabled ||
                (!state.pendingInsert && (!state.reviewed || !state.selectedSlideIds.length))
              }
              onClick={() => void insert()}
            >
              {state.busy === "insert"
                ? "Inserting slides…"
                : state.pendingInsert
                  ? "Retry exact insertion"
                  : `Insert ${state.selectedSlideIds.length} reviewed slides`}
            </button>
            <p className={styles.help}>
              Inserted slides remain editable on the canvas. The outline source and AI review
              warning stay attached.
            </p>
          </>
        ) : null}
        {state.pendingInsert && !state.job?.proposal ? (
          <button type="button" disabled={disabled} onClick={() => void insert()}>
            {state.busy === "insert" ? "Recovering insertion…" : "Retry exact insertion"}
          </button>
        ) : null}
        {state.job || recovered || state.error ? (
          <div className={styles.actions}>
            <button
              type="button"
              disabled={disabled}
              onClick={() => void controller.current?.refresh()}
            >
              Recover proposal
            </button>
            {state.error && state.job?.proposal && !state.pendingInsert ? (
              <button type="button" disabled={disabled} onClick={() => void reloadDraft()}>
                Reload saved deck
              </button>
            ) : null}
            {!state.pendingInsert ? (
              <button type="button" disabled={disabled} onClick={startAgain}>
                Start another outline
              </button>
            ) : (
              <p className={styles.help}>
                Recover the insertion acknowledgement before changing the selection or editing the
                deck.
              </p>
            )}
          </div>
        ) : null}
      </section>
    </div>
  );
}
