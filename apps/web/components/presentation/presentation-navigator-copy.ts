export type PresentationNavigatorMessage = keyof typeof rows;
export function presentationNavigatorCopy(locale: SupportedLocale) {
  const index = locales.indexOf(locale as (typeof locales)[number]);
  return (message: PresentationNavigatorMessage, values: Record<string, string> = {}) => {
    const text: string = index < 0 ? message : rows[message][index]!;
    return text.replace(/\{(\w+)\}/g, (token, key: string) => values[key] ?? token);
  };
}
