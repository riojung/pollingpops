"use client";

import { useEffect, useId, useRef, useState } from "react";
import type {
  PresentationQuestionSuggestionSource,
  PresentationQuestionSuggestionsProposal,
  SupportedLocale,
} from "@openround/contracts";
import { AUTH_CHANGE_EVENT, humanError } from "../../lib/api";
import {
  createPresentationQuestionSuggestions,
  fetchQuestionSuggestionsStatus,
  initialQuestionSuggestionsState,
  parseQuestionSuggestionsRecovery,
  questionSuggestionsTargetMatches,
  type QuestionSuggestionsInsertedReceipt,
  type QuestionSuggestionsRecovery,
  type QuestionSuggestionsState,
  type QuestionSuggestionsStatus,
  type QuestionSuggestionsTarget,
} from "../../lib/presentation-question-suggestions-client";
import { questionSuggestionsCopy, questionSuggestionsFeedback } from "./question-suggestions-copy";
import styles from "./presentation-question-suggestions.module.css";

interface Props {
  locale?: SupportedLocale;
  presentationId: string;
  actorKey: string;
  canEdit: boolean;
  open: boolean;
  target: QuestionSuggestionsTarget | null;
  onInserted: (receipt: QuestionSuggestionsInsertedReceipt) => Promise<void>;
  onReloadTarget: (
    binding: Pick<QuestionSuggestionsRecovery, "blockId" | "sourceDigest" | "expectedRevision">,
  ) => Promise<QuestionSuggestionsTarget>;
  onReloadForInvalidRecovery: (canContinue: () => boolean) => Promise<void>;
  onClose: () => void;
  onPendingChange: (pending: boolean) => void;
  onRecoveryChange: (present: boolean) => void;
}
type Controller = ReturnType<typeof createPresentationQuestionSuggestions>;

export function QuestionSuggestionsSourceReview({
  source,
  locale = "en-CA",
}: {
  source: PresentationQuestionSuggestionSource;
  locale?: SupportedLocale;
}) {
  const t = questionSuggestionsCopy(locale);
  return (
    <section className={styles.source} aria-label={t("Private source context")} lang={locale}>
      <h3>{t("Private source context")}</h3>
      <p>
        {t(
          "Only this slide’s complete title and body text are used. Speaker notes, earlier citations, images, tables, charts and closed interaction content are not sent or interpreted.",
        )}
      </p>
      {source.readingOrder.map((id) => {
        const title = id === source.title.nodeId;
        const index = source.body.findIndex((body) => body.nodeId === id);
        const node = title ? source.title : source.body[index];
        return node ? (
          <article key={id} data-question-suggestion-source-node={id}>
            <h4>{title ? t("Slide title") : t("Body text {number}", { number: index + 1 })}</h4>
            <p className={styles.sourceText} lang={node.lang ?? ""}>
              {node.text}
            </p>
          </article>
        ) : null;
      })}
    </section>
  );
}

export function QuestionSuggestionsProposalReview({
  proposal,
  suggestionId,
  reviewed,
  disabled,
  onSelect,
  onReview,
  locale = "en-CA",
}: {
  proposal: PresentationQuestionSuggestionsProposal;
  suggestionId: string | null;
  reviewed: boolean;
  disabled: boolean;
  onSelect: (id: string) => void;
  onReview: (reviewed: boolean) => void;
  locale?: SupportedLocale;
}) {
  const choiceId = useId();
  const t = questionSuggestionsCopy(locale);
  const warning = questionSuggestionsFeedback(locale, proposal.reviewWarning);
  return (
    <section aria-label={t("Review both suggested questions")} lang={locale}>
      <h3>{t("Review both questions")}</h3>
      <p className={styles.warning} lang={warning.lang}>
        {warning.text}
      </p>
      <p className={styles.help}>
        {t("Generated by")}{" "}
        <span lang="">
          {proposal.provider} / {proposal.model}
        </span>
        {" · "}
        <time lang="" dateTime={proposal.generatedAt}>
          {proposal.generatedAt}
        </time>
        . {t("Suggestions use English; source wording keeps its authored language.")}
      </p>
      <p className={styles.settings}>
        {t(
          "Both questions: Opinion · 0 points · confidence off · no correct answer · no linked recheck · 20-second response time. Participants write an open-text response.",
        )}
      </p>
      <fieldset className={styles.choices} disabled={disabled}>
        <legend>{t("Choose one question to insert")}</legend>
        {proposal.suggestions.map((suggestion) => (
          <article key={suggestion.id}>
            <label>
              <input
                type="radio"
                name={`${choiceId}-suggestion`}
                value={suggestion.id}
                checked={suggestion.id === suggestionId}
                onChange={() => onSelect(suggestion.id)}
              />
              <span>
                <strong>
                  {suggestion.kind === "discussion"
                    ? t("Discussion question")
                    : t("Reflection question")}
                </strong>
              </span>
            </label>
            <p className={styles.prompt} lang="en">
              {suggestion.prompt}
            </p>
            <h4>{t("Exact source excerpts")}</h4>
            {suggestion.citations.map((citation, index) => {
              const bodyIndex = /^body (\d+) paragraph /u.exec(citation.locator)?.[1];
              const source =
                citation.locator === "title"
                  ? proposal.source.title
                  : bodyIndex
                    ? proposal.source.body[Number(bodyIndex) - 1]
                    : null;
              return (
                <div key={index}>
                  <strong lang="en-CA">{citation.locator}</strong>
                  <blockquote lang={source?.lang ?? ""}>{citation.excerpt}</blockquote>
                </div>
              );
            })}
          </article>
        ))}
      </fieldset>
      <p className={styles.help}>
        {t(
          "Exact excerpts identify earlier source wording. They do not independently verify either question’s framing or claims.",
        )}
      </p>
      <QuestionSuggestionsSourceReview source={proposal.source} locale={locale} />
      <label className={styles.reviewCheck}>
        <input
          type="checkbox"
          checked={reviewed}
          disabled={disabled}
          onChange={(event) => onReview(event.target.checked)}
        />
        <span>
          {t(
            "I reviewed both complete questions, their settings and exact source excerpts, including unsupported framing or claims.",
          )}
        </span>
      </label>
    </section>
  );
}

export function PresentationQuestionSuggestions(props: Props) {
  const { presentationId, actorKey, canEdit, open } = props;
  const locale = props.locale ?? "en-CA";
  const t = questionSuggestionsCopy(locale);
  const storageKey = `presentation-question-suggestions:v1:${actorKey}:${presentationId}`;
  const [state, setState] = useState<QuestionSuggestionsState>(initialQuestionSuggestionsState);
  const [status, setStatus] = useState<QuestionSuggestionsStatus | null>(null);
  const [availabilityError, setAvailabilityError] = useState("");
  const [attempt, setAttempt] = useState(0);
  const [formError, setFormError] = useState("");
  const [authInvalid, setAuthInvalid] = useState(false);
  const [invalidRecovery, setInvalidRecovery] = useState(false);
  const [invalidReviewed, setInvalidReviewed] = useState(false);
  const [resetBusy, setResetBusy] = useState(false);
  const [reloadBusy, setReloadBusy] = useState(false);
  const [reloadedTarget, setReloadedTarget] = useState<QuestionSuggestionsTarget | null>(null);
  const latest = useRef(props);
  latest.current = props;
  const authFence = useRef(!canEdit);
  if (!canEdit) authFence.current = true;
  const allowed = useRef(canEdit);
  allowed.current = canEdit && !authInvalid && !authFence.current;
  const controller = useRef<Controller | null>(null);
  const activeSession = useRef<{
    session: Controller;
    actorKey: string;
    presentationId: string;
    storageKey: string;
  } | null>(null);
  const invalid = useRef(false);
  const resetFlight = useRef<object | null>(null);
  const reloadFlight = useRef<object | null>(null);
  const dialog = useRef<HTMLDialogElement>(null);
  const suppressFocusReturn = useRef(false);
  const titleId = useId();
  const descriptionId = useId();

  useEffect(() => {
    const session = createPresentationQuestionSuggestions({
      actorKey,
      presentationId,
      canEdit: () =>
        allowed.current &&
        latest.current.actorKey === actorKey &&
        latest.current.presentationId === presentationId,
      persist: (value) => {
        if (value) window.sessionStorage.setItem(storageKey, JSON.stringify(value));
        else window.sessionStorage.removeItem(storageKey);
      },
      onState: (next) => {
        setState(next);
        latest.current.onPendingChange(next.pending || reloadFlight.current !== null);
        latest.current.onRecoveryChange(Boolean(next.recovery));
      },
      onInserted: async (receipt) => {
        await latest.current.onInserted(receipt);
        if (
          !allowed.current ||
          latest.current.actorKey !== actorKey ||
          latest.current.presentationId !== presentationId
        )
          throw new Error("Editor permission changed. Recover this insertion after reloading.");
      },
    });
    controller.current = session;
    const scope = { session, actorKey, presentationId, storageKey };
    activeSession.current = scope;
    invalid.current = false;
    resetFlight.current = null;
    reloadFlight.current = null;
    setInvalidRecovery(false);
    setInvalidReviewed(false);
    setResetBusy(false);
    setReloadBusy(false);
    setFormError("");
    setReloadedTarget(null);
    setState(initialQuestionSuggestionsState());
    latest.current.onPendingChange(false);
    latest.current.onRecoveryChange(false);
    try {
      const raw = window.sessionStorage.getItem(storageKey);
      if (raw !== null) session.restore(JSON.parse(raw));
    } catch (error) {
      invalid.current = true;
      setInvalidRecovery(true);
      setFormError(humanError(error));
      latest.current.onPendingChange(true);
      latest.current.onRecoveryChange(true);
    }
    const authChanged = () => {
      authFence.current = true;
      allowed.current = false;
      session.cancel();
      setAuthInvalid(true);
      setReloadedTarget(null);
      setState((current) => ({
        ...current,
        job: null,
        reviewed: false,
        busy: null,
        error: "Your sign-in changed. Reload the editor before using discussion suggestions.",
      }));
    };
    window.addEventListener(AUTH_CHANGE_EVENT, authChanged);
    return () => {
      if (activeSession.current === scope) activeSession.current = null;
      session.cancel();
      window.removeEventListener(AUTH_CHANGE_EVENT, authChanged);
    };
  }, [actorKey, presentationId, storageKey]);

  useEffect(() => {
    setReloadedTarget(null);
  }, [props.target]);
  useEffect(() => {
    if (!canEdit) {
      allowed.current = false;
      controller.current?.cancel();
      setAuthInvalid(true);
    }
  }, [canEdit]);
  useEffect(() => {
    if (!open || !canEdit || authInvalid) return;
    const abort = new AbortController();
    setStatus(null);
    setAvailabilityError("");
    void fetchQuestionSuggestionsStatus(presentationId, abort.signal)
      .then((value) => {
        if (!abort.signal.aborted && allowed.current) setStatus(value);
      })
      .catch((error) => {
        if (!abort.signal.aborted && allowed.current) setAvailabilityError(humanError(error));
      });
    return () => abort.abort();
  }, [open, canEdit, authInvalid, actorKey, presentationId, attempt]);
  useEffect(() => {
    if (!open) return;
    suppressFocusReturn.current = false;
    const target = dialog.current;
    const previous = document.activeElement instanceof HTMLElement ? document.activeElement : null;
    if (target && !target.open) target.showModal();
    return () => {
      if (target?.open) target.close();
      if (suppressFocusReturn.current) return;
      const returnTarget =
        previous?.isConnected &&
        previous !== document.body &&
        previous !== document.documentElement &&
        !previous.closest("[inert]")
          ? previous
          : document.querySelector<HTMLElement>(
              "[data-question-suggestions-resume], [data-question-suggestions-trigger]",
            );
      if (returnTarget && !returnTarget.matches(":disabled") && !returnTarget.closest("[inert]"))
        returnTarget.focus({ preventScroll: true });
    };
  }, [open]);
  useEffect(() => {
    if (!open || state.busy || !["pending", "processing"].includes(state.job?.status ?? "")) return;
    const timer = window.setTimeout(() => void controller.current?.refresh(), 2000);
    return () => window.clearTimeout(timer);
  }, [open, state.job, state.busy]);

  const scopeCurrent = (scope: NonNullable<typeof activeSession.current>) =>
    activeSession.current === scope &&
    allowed.current &&
    latest.current.actorKey === scope.actorKey &&
    latest.current.presentationId === scope.presentationId;
  async function run(action: () => unknown | Promise<unknown>) {
    const scope = activeSession.current;
    if (!scope || !scopeCurrent(scope) || reloadFlight.current) return;
    setFormError("");
    try {
      await action();
    } catch (error) {
      if (scopeCurrent(scope)) setFormError(humanError(error));
    }
  }
  async function reloadSource() {
    const scope = activeSession.current;
    const saved = scope?.session.state().recovery;
    if (
      !scope ||
      !saved ||
      !scopeCurrent(scope) ||
      reloadFlight.current ||
      saved.insertBody ||
      scope.session.state().pending
    )
      return;
    const flight = {};
    reloadFlight.current = flight;
    setReloadBusy(true);
    latest.current.onPendingChange(true);
    try {
      const target = await latest.current.onReloadTarget({
        blockId: saved.blockId,
        sourceDigest: saved.sourceDigest,
        expectedRevision: saved.expectedRevision,
      });
      if (scopeCurrent(scope) && scope.session.rebase(target)) setReloadedTarget(target);
    } finally {
      if (reloadFlight.current === flight) {
        reloadFlight.current = null;
        if (scopeCurrent(scope)) {
          setReloadBusy(false);
          latest.current.onPendingChange(scope.session.state().pending);
        }
      }
    }
  }
  async function insertReviewed(target: QuestionSuggestionsTarget | null) {
    const scope = activeSession.current;
    if (!scope || !scopeCurrent(scope) || reloadFlight.current) return;
    if (await scope.session.insert(target)) {
      if (!scopeCurrent(scope)) return;
      suppressFocusReturn.current = true;
      latest.current.onClose();
    }
  }
  async function clearInvalidRecovery() {
    const scope = activeSession.current;
    if (
      !scope ||
      !invalid.current ||
      !invalidReviewed ||
      resetFlight.current ||
      !scopeCurrent(scope)
    )
      return;
    const flight = {};
    resetFlight.current = flight;
    setResetBusy(true);
    setFormError("");
    const current = () => scopeCurrent(scope);
    function restoreValid(raw: string | null) {
      if (raw === null) return false;
      let saved: QuestionSuggestionsRecovery;
      try {
        saved = parseQuestionSuggestionsRecovery(
          JSON.parse(raw),
          scope!.actorKey,
          scope!.presentationId,
        );
      } catch {
        return false;
      }
      scope!.session.restore(saved);
      invalid.current = false;
      setInvalidRecovery(false);
      setInvalidReviewed(false);
      setFormError("A valid saved request was found. Recover it instead of clearing it.");
      return true;
    }
    try {
      const before = window.sessionStorage.getItem(scope.storageKey);
      await latest.current.onReloadForInvalidRecovery(current);
      if (!current()) return;
      const after = window.sessionStorage.getItem(scope.storageKey);
      if (restoreValid(after)) return;
      if (before !== after) {
        setInvalidReviewed(false);
        throw new Error(
          "The saved recovery record changed while loading. Review the warning and try again.",
        );
      }
      window.sessionStorage.removeItem(scope.storageKey);
      const remaining = window.sessionStorage.getItem(scope.storageKey);
      if (remaining !== null) {
        if (restoreValid(remaining)) return;
        throw new Error(
          "The invalid recovery record could not be cleared. Allow tab storage and retry.",
        );
      }
      if (!current()) return;
      invalid.current = false;
      setInvalidRecovery(false);
      setInvalidReviewed(false);
      setReloadedTarget(null);
      setState(initialQuestionSuggestionsState());
      latest.current.onPendingChange(false);
      latest.current.onRecoveryChange(false);
      latest.current.onClose();
    } catch (error) {
      if (current()) setFormError(humanError(error));
    } finally {
      if (resetFlight.current === flight) {
        resetFlight.current = null;
        if (current()) setResetBusy(false);
      }
    }
  }
  const target = reloadedTarget ?? props.target;
  const saved = state.recovery;
  const proposal = canEdit && !authInvalid ? state.job?.proposal : null;
  const disabled = Boolean(state.busy) || resetBusy || reloadBusy || !canEdit || authInvalid;
  const unavailable =
    !status?.enabled || status.remaining === 0 || status.active >= status.maxActiveJobs;
  const sameSource = Boolean(saved && target && questionSuggestionsTargetMatches(target, saved));
  const sourceMatches = sameSource && target?.expectedRevision === saved?.expectedRevision;
  const availabilityFeedback = questionSuggestionsFeedback(locale, availabilityError);
  const errorFeedback = questionSuggestionsFeedback(locale, formError || state.error);
  const messageFeedback = questionSuggestionsFeedback(locale, state.message);
  const jobFeedback = questionSuggestionsFeedback(locale, state.job?.error?.message ?? "");
  if (!open) return null;
  return (
    <dialog
      ref={dialog}
      className={styles.dialog}
      aria-labelledby={titleId}
      aria-describedby={descriptionId}
      aria-modal="true"
      lang={locale}
      onCancel={(event) => {
        event.preventDefault();
        latest.current.onClose();
      }}
      onClose={() => {
        if (latest.current.open) latest.current.onClose();
      }}
    >
      <header className={styles.heading}>
        <div>
          <p className={styles.help}>{t("Optional AI assistance")}</p>
          <h2 id={titleId}>{t("Review discussion suggestions")}</h2>
        </div>
        <button type="button" onClick={props.onClose}>
          {t("Close")}
        </button>
      </header>
      <p id={descriptionId}>
        {t(
          "Generate two source-specific English discussion and reflection questions. Review both and choose one to insert after this exact slide. Generation leaves the presentation unchanged.",
        )}
      </p>
      <p className={styles.help}>
        {t(
          "Free question starters and manual questions remain available. This is optional; no generation starts until you choose Generate.",
        )}
      </p>
      <div role="status" aria-live="polite" className={styles.notice}>
        {!canEdit ? (
          t("Editor permission is required.")
        ) : authInvalid ? (
          t("Reload after your sign-in or permission changes.")
        ) : status ? (
          <>
            <p>
              {status.monthlyLimit === null
                ? t("{used} AI jobs used this month; operator-configured allowance.", {
                    used: status.used,
                  })
                : t("{used} of {limit} AI jobs used this month ({remaining} remaining).", {
                    used: status.used,
                    limit: status.monthlyLimit,
                    remaining: status.remaining ?? "",
                  })}{" "}
              {t("One generation uses one AI job. Review and insertion use no additional job.")}
            </p>
            {!status.enabled ? (
              <p>{t("AI assistance is disabled on this deployment.")}</p>
            ) : status.remaining === 0 ? (
              <p>{t("Your monthly AI allowance is used.")}</p>
            ) : status.active >= status.maxActiveJobs ? (
              <p>{t("Two AI jobs are already active. Retry availability after a job finishes.")}</p>
            ) : null}
          </>
        ) : (
          t("Checking AI availability and allowance…")
        )}
      </div>
      <button type="button" disabled={disabled} onClick={() => setAttempt((value) => value + 1)}>
        {t("Retry availability")}
      </button>
      {availabilityError ? (
        <p role="alert" lang={availabilityFeedback.lang}>
          {availabilityFeedback.text}
        </p>
      ) : null}
      {formError || state.error ? (
        <p role="alert" className={styles.error} lang={errorFeedback.lang}>
          {errorFeedback.text}
        </p>
      ) : null}
      {state.message ? (
        <p role="status" lang={messageFeedback.lang}>
          {messageFeedback.text}
        </p>
      ) : null}
      {reloadBusy ? <p role="status">{t("Reloading the exact saved source…")}</p> : null}
      {invalidRecovery ? (
        <section className={styles.warning} aria-label={t("Unverifiable discussion recovery")}>
          <h3>{t("Saved discussion recovery could not be verified")}</h3>
          <p>
            {t(
              "A previous request may already have inserted a question. Reload the current saved deck before clearing this invalid tab record. Other saved requests and local recovery copies are retained.",
            )}
          </p>
          <label className={styles.reviewCheck}>
            <input
              type="checkbox"
              checked={invalidReviewed}
              disabled={disabled}
              onChange={(event) => setInvalidReviewed(event.target.checked)}
            />
            <span>
              {t(
                "I understand the saved request cannot be recovered and a question may already have been inserted.",
              )}
            </span>
          </label>
          <button
            type="button"
            disabled={disabled || !invalidReviewed}
            onClick={() => void clearInvalidRecovery()}
          >
            {resetBusy
              ? t("Reloading saved deck…")
              : t("Reload saved deck and clear invalid recovery")}
          </button>
        </section>
      ) : null}
      {!invalidRecovery && !saved && target && canEdit && !authInvalid ? (
        <>
          <QuestionSuggestionsSourceReview source={target.source} locale={locale} />
          <button
            type="button"
            disabled={disabled || unavailable}
            onClick={() => void run(() => controller.current?.generate(target))}
          >
            {t("Generate discussion suggestions")}
          </button>
        </>
      ) : null}
      {state.job ? (
        <p role="status">
          {state.job.status === "pending"
            ? t("Suggestions queued.")
            : state.job.status === "processing"
              ? t("Preparing questions for review…")
              : state.job.status === "ready"
                ? t("Ready for review.")
                : state.job.status === "failed"
                  ? t("Suggestions failed.")
                  : t("Suggestions expired.")}
          {state.job.error ? (
            <>
              {" "}
              <span lang={jobFeedback.lang}>{jobFeedback.text}</span>
            </>
          ) : null}
        </p>
      ) : null}
      {proposal ? (
        <QuestionSuggestionsProposalReview
          proposal={proposal}
          suggestionId={saved?.suggestionId ?? null}
          reviewed={state.reviewed}
          disabled={disabled || state.pending}
          locale={locale}
          onSelect={(id) => controller.current?.select(id)}
          onReview={(value) => controller.current?.review(value)}
        />
      ) : null}
      {proposal && !sourceMatches && !saved?.insertBody && !reloadBusy ? (
        <p role="status" className={styles.notice}>
          {target && !sameSource
            ? t(
                "The source changed. Discard this proposal, then generate suggestions from the current saved slide.",
              )
            : target
              ? t(
                  "The saved deck revision changed. Reload exact source and review both questions again before inserting.",
                )
              : t("Reload exact source before inserting this proposal.")}
        </p>
      ) : null}
      {saved ? (
        <div className={styles.notice}>
          {saved.insertBody ? (
            <button
              type="button"
              disabled={disabled}
              onClick={() => void run(() => insertReviewed(null))}
            >
              {t("Retry exact insertion")}
            </button>
          ) : (
            <>
              <button
                type="button"
                disabled={disabled}
                onClick={() => void run(() => controller.current?.retry())}
              >
                {t("Recover saved request")}
              </button>
              <button
                type="button"
                disabled={disabled || state.pending}
                onClick={() => void run(reloadSource)}
              >
                {t("Reload exact source")}
              </button>
              <button
                type="button"
                disabled={disabled || state.pending}
                onClick={() =>
                  void run(() => {
                    if (controller.current?.reset()) {
                      setReloadedTarget(null);
                      latest.current.onClose();
                    }
                  })
                }
              >
                {t("Discard proposal")}
              </button>
            </>
          )}
        </div>
      ) : null}
      <div className={styles.actions}>
        {proposal ? (
          <button
            type="button"
            disabled={disabled || state.pending || !state.reviewed || !sourceMatches}
            onClick={() => void run(() => insertReviewed(target))}
          >
            {t("Insert reviewed question")}
          </button>
        ) : null}
        <button type="button" onClick={props.onClose}>
          {t("Close review")}
        </button>
      </div>
    </dialog>
  );
}
