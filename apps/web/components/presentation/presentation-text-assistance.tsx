"use client";

import { useEffect, useRef, useState, type KeyboardEvent } from "react";
import {
  PRESENTATION_TEXT_LANGUAGES,
  presentationTextLanguageLabel,
  PresentationTextLanguageSchema,
  type PresentationTextLanguage,
  type PresentationTextAssistanceProposal,
  type SupportedLocale,
} from "@openround/contracts";
import { AUTH_CHANGE_EVENT, humanError } from "../../lib/api";
import {
  createPresentationTextAssistance,
  fetchTextAssistanceStatus,
  initialTextAssistanceState,
  parseTextAssistanceRecovery,
  type TextAssistanceAppliedReceipt,
  type TextAssistanceRecovery,
  type TextAssistanceState,
  type TextAssistanceStatus,
  type TextAssistanceTarget,
} from "../../lib/presentation-text-assistance-client";
import { textAssistanceCopy, textAssistanceFeedback } from "./text-assistance-copy";
import styles from "./presentation-assistance.module.css";

const focusable =
  'button:not([disabled]), input:not([disabled]), textarea:not([disabled]), select:not([disabled]), [tabindex="0"]';
type Controller = ReturnType<typeof createPresentationTextAssistance>;
interface Props {
  locale?: SupportedLocale;
  presentationId: string;
  actorKey: string;
  canEdit: boolean;
  open: boolean;
  target: TextAssistanceTarget | null;
  citations: readonly { locator: string; excerpt: string }[];
  onApplied: (receipt: TextAssistanceAppliedReceipt) => Promise<void>;
  onReloadTarget: (
    target: Pick<
      TextAssistanceRecovery,
      | "blockId"
      | "nodeId"
      | "role"
      | "operation"
      | "sourceDigest"
      | "targetLanguage"
      | "sourceLanguage"
    >,
  ) => Promise<TextAssistanceTarget>;
  onReloadForInvalidRecovery: (canContinue: () => boolean) => Promise<void>;
  onClose: () => void;
  onPendingChange: (pending: boolean) => void;
  onRecoveryChange: (present: boolean) => void;
}

export const textAssistanceLanguageLabel = presentationTextLanguageLabel;

/** Canonical request languages stay separate from the selected UI locale. */
export function textAssistanceLanguageDisplay(
  language: PresentationTextLanguage,
  locale: SupportedLocale = "en-CA",
) {
  const fallback = { text: textAssistanceLanguageLabel(language), lang: "en-CA" };
  if (locale === "en-CA") return fallback;
  try {
    const text = new Intl.DisplayNames([locale], { type: "language", fallback: "none" }).of(
      language,
    );
    return text ? { text, lang: locale } : fallback;
  } catch {
    return fallback;
  }
}

function LanguageName({
  language,
  locale,
}: {
  language: PresentationTextLanguage;
  locale: SupportedLocale;
}) {
  const display = textAssistanceLanguageDisplay(language, locale);
  return <span lang={display.lang}>{display.text}</span>;
}

export function TextAssistanceProposalReview({
  proposal,
  citations,
  reviewed,
  disabled,
  onReview,
  locale = "en-CA",
}: {
  locale?: SupportedLocale;
  proposal: PresentationTextAssistanceProposal;
  citations: Props["citations"];
  reviewed: boolean;
  disabled: boolean;
  onReview: (reviewed: boolean) => void;
}) {
  const copy = textAssistanceCopy(locale);
  const warning = textAssistanceFeedback(locale, proposal.reviewWarning);
  const metadata: Record<string, string> = {
    provider: proposal.provider,
    model: proposal.model,
    generatedAt: proposal.generatedAt,
  };
  return (
    <section aria-label={copy("Review proposed text")} className={styles.proposal} lang={locale}>
      <h3>{copy("Review proposed text")}</h3>
      <p className={styles.warning} lang={warning.lang}>
        {warning.text}
      </p>
      <p className={styles.help}>
        {copy("Generated by {provider} / {model} at {generatedAt}. This is unverified wording.")
          .split(/(\{\w+\})/g)
          .map((part, index) =>
            metadata[part.slice(1, -1)] !== undefined ? (
              <span key={index} lang="">
                {metadata[part.slice(1, -1)]}
              </span>
            ) : (
              part
            ),
          )}
      </p>
      {proposal.operation === "translate" ? (
        <p>
          <strong>{copy("Target language:")}</strong>{" "}
          <LanguageName language={proposal.targetLanguage!} locale={locale} />.{" "}
          {copy("Original language:")}{" "}
          {proposal.sourceLanguage ? (
            <LanguageName language={proposal.sourceLanguage} locale={locale} />
          ) : (
            copy("Not marked")
          )}
          .
        </p>
      ) : null}
      <article className={styles.slide}>
        <h4>{copy("Original text")}</h4>
        <p
          className={styles.slideBody}
          lang={proposal.operation === "translate" ? (proposal.sourceLanguage ?? "") : ""}
        >
          {proposal.originalText}
        </p>
      </article>
      <article className={styles.slide}>
        <h4>
          {proposal.operation === "translate"
            ? copy("Translation — {language}")
                .split("{language}")
                .map((part, index) => (
                  <span key={index}>
                    {index ? (
                      <LanguageName language={proposal.targetLanguage!} locale={locale} />
                    ) : null}
                    {part}
                  </span>
                ))
            : copy("Proposed text")}
        </h4>
        <p
          className={styles.slideBody}
          lang={proposal.operation === "translate" ? proposal.targetLanguage : ""}
        >
          {proposal.text}
        </p>
      </article>
      <p className={styles.help}>
        {copy(
          "Previous citations provide context for earlier text. They do not verify this proposed wording.",
        )}
      </p>
      {citations.length ? (
        <ul>
          {citations.map((citation, index) => (
            <li key={`${citation.locator}:${index}`}>
              <strong lang="">{citation.locator}</strong>
              <blockquote className={styles.slideBody} lang="">
                {citation.excerpt}
              </blockquote>
            </li>
          ))}
        </ul>
      ) : null}
      <label className={styles.check}>
        <input
          type="checkbox"
          checked={reviewed}
          disabled={disabled}
          onChange={(event) => onReview(event.target.checked)}
        />
        <span>
          {proposal.operation === "translate"
            ? copy(
                "I reviewed the complete original and translated wording, including meaning, terminology, unsupported claims and existing citations.",
              )
            : copy(
                "I reviewed the complete original and proposed wording, including unsupported claims and existing citations.",
              )}
        </span>
      </label>
    </section>
  );
}

export function PresentationTextAssistance(props: Props) {
  const { presentationId, actorKey, canEdit, open, locale = "en-CA" } = props;
  const copy = textAssistanceCopy(locale);
  const storageKey = `presentation-text-assistance:v1:${actorKey}:${presentationId}`;
  const [state, setState] = useState<TextAssistanceState>(initialTextAssistanceState);
  const [status, setStatus] = useState<TextAssistanceStatus | null>(null);
  const [availabilityError, setAvailabilityError] = useState("");
  const [attempt, setAttempt] = useState(0);
  const [formError, setFormError] = useState("");
  const [authInvalid, setAuthInvalid] = useState(false);
  const [targetInvalid, setTargetInvalid] = useState(false);
  const [targetLanguage, setTargetLanguage] = useState<PresentationTextLanguage | "">("");
  const [invalidRecovery, setInvalidRecovery] = useState(false);
  const [invalidRecoveryReviewed, setInvalidRecoveryReviewed] = useState(false);
  const [invalidResetBusy, setInvalidResetBusy] = useState(false);
  const invalidRecoveryRef = useRef(false);
  const resetFlight = useRef<object | null>(null);
  const activeSession = useRef<{
    session: Controller;
    actorKey: string;
    presentationId: string;
    storageKey: string;
  } | null>(null);
  const [reloadedTarget, setReloadedTarget] = useState<TextAssistanceTarget | null>(null);
  const controller = useRef<Controller | null>(null);
  const dialog = useRef<HTMLDivElement>(null);
  const latest = useRef(props);
  latest.current = props;
  const allowed = useRef(canEdit);
  allowed.current = canEdit && !authInvalid;

  useEffect(() => {
    const session = createPresentationTextAssistance({
      actorKey,
      presentationId,
      canEdit: () => allowed.current && latest.current.actorKey === actorKey,
      persist: (value) => {
        if (value) window.sessionStorage.setItem(storageKey, JSON.stringify(value));
        else window.sessionStorage.removeItem(storageKey);
      },
      onState: (next) => {
        setState(next);
        latest.current.onPendingChange(next.pending);
        latest.current.onRecoveryChange(Boolean(next.recovery));
      },
      onApplied: async (receipt) => {
        await latest.current.onApplied(receipt);
        latest.current.onClose();
      },
    });
    controller.current = session;
    const scope = { session, actorKey, presentationId, storageKey };
    activeSession.current = scope;
    invalidRecoveryRef.current = false;
    resetFlight.current = null;
    setInvalidRecovery(false);
    setInvalidRecoveryReviewed(false);
    setInvalidResetBusy(false);
    setFormError("");
    setTargetLanguage("");
    setState(initialTextAssistanceState());
    latest.current.onPendingChange(false);
    latest.current.onRecoveryChange(false);
    try {
      const raw = window.sessionStorage.getItem(storageKey);
      if (raw !== null) session.restore(JSON.parse(raw));
    } catch (error) {
      setFormError(humanError(error));
      // An unknown receipt may describe an accepted Apply. Clearing it requires a fresh deck read.
      invalidRecoveryRef.current = true;
      setInvalidRecovery(true);
      latest.current.onPendingChange(true);
      latest.current.onRecoveryChange(true);
    }
    const authChanged = () => {
      allowed.current = false;
      session.cancel();
      setAuthInvalid(true);
      setReloadedTarget(null);
      setState({
        ...initialTextAssistanceState(),
        error: "Your sign-in changed. Reload the editor before using text assistance.",
      });
    };
    window.addEventListener(AUTH_CHANGE_EVENT, authChanged);
    return () => {
      if (activeSession.current === scope) activeSession.current = null;
      session.cancel();
      window.removeEventListener(AUTH_CHANGE_EVENT, authChanged);
    };
  }, [actorKey, presentationId, storageKey, canEdit]);

  useEffect(() => {
    setReloadedTarget(null);
    setTargetInvalid(false);
    setTargetLanguage(
      props.target?.operation === "translate" ? (props.target.targetLanguage ?? "") : "",
    );
  }, [props.target]);

  useEffect(() => {
    if (!open || !canEdit || authInvalid) return;
    const abort = new AbortController();
    setStatus(null);
    setAvailabilityError("");
    void fetchTextAssistanceStatus(presentationId, abort.signal)
      .then((value) => {
        if (!abort.signal.aborted) setStatus(value);
      })
      .catch((error) => {
        if (!abort.signal.aborted) setAvailabilityError(humanError(error));
      });
    return () => abort.abort();
  }, [open, canEdit, authInvalid, presentationId, attempt]);
  useEffect(() => {
    if (!open) return;
    const previous = document.activeElement instanceof HTMLElement ? document.activeElement : null;
    (dialog.current?.querySelector<HTMLElement>(focusable) ?? dialog.current)?.focus();
    return () => {
      const focusTarget =
        previous?.isConnected && !previous.closest("[inert]")
          ? previous
          : document.querySelector<HTMLElement>("[data-text-assistance-resume]");
      focusTarget?.focus();
    };
  }, [open]);
  useEffect(() => {
    if (!open || state.busy || !["pending", "processing"].includes(state.job?.status ?? "")) return;
    const timer = window.setTimeout(() => void controller.current?.refresh(), 2000);
    return () => window.clearTimeout(timer);
  }, [open, state.job, state.busy]);

  function keyDown(event: KeyboardEvent<HTMLDivElement>) {
    if (event.key === "Escape") {
      event.preventDefault();
      props.onClose();
      return;
    }
    if (event.key !== "Tab") return;
    const fields = [...event.currentTarget.querySelectorAll<HTMLElement>(focusable)].filter(
      (field) => field.offsetParent !== null,
    );
    const first = fields[0];
    const last = fields.at(-1);
    if (!first || !last) {
      event.preventDefault();
      event.currentTarget.focus();
    } else if (event.shiftKey && document.activeElement === first) {
      event.preventDefault();
      last.focus();
    } else if (!event.shiftKey && document.activeElement === last) {
      event.preventDefault();
      first.focus();
    }
  }
  async function resetInvalidRecovery() {
    const scope = activeSession.current;
    if (!scope || !invalidRecoveryRef.current || !invalidRecoveryReviewed || resetFlight.current)
      return;
    const current = () =>
      activeSession.current === scope &&
      allowed.current &&
      latest.current.actorKey === scope.actorKey &&
      latest.current.presentationId === scope.presentationId;
    if (!current()) return;
    const flight = {};
    resetFlight.current = flight;
    setInvalidResetBusy(true);
    setFormError("");
    function restoreValid(raw: string | null) {
      if (raw === null) return false;
      let recovery: TextAssistanceRecovery;
      try {
        recovery = parseTextAssistanceRecovery(
          JSON.parse(raw),
          scope!.actorKey,
          scope!.presentationId,
        );
      } catch {
        return false;
      }
      scope!.session.restore(recovery);
      invalidRecoveryRef.current = false;
      setInvalidRecovery(false);
      setInvalidRecoveryReviewed(false);
      setFormError("A valid saved request was found. Recover that request instead of clearing it.");
      return true;
    }
    try {
      const raw = window.sessionStorage.getItem(scope.storageKey);
      await latest.current.onReloadForInvalidRecovery(current);
      if (!current()) return;
      const refreshed = window.sessionStorage.getItem(scope.storageKey);
      if (restoreValid(refreshed)) return;
      if (refreshed !== raw) {
        setInvalidRecoveryReviewed(false);
        throw new Error(
          "The saved recovery record changed while loading. Review the warning and try again.",
        );
      }
      window.sessionStorage.removeItem(scope.storageKey);
      const remaining = window.sessionStorage.getItem(scope.storageKey);
      if (remaining !== null) {
        if (restoreValid(remaining)) return;
        throw new Error(
          "The invalid recovery record could not be cleared. Allow tab storage and retry.",
        );
      }
      if (!current()) return;
      invalidRecoveryRef.current = false;
      setInvalidRecovery(false);
      setInvalidRecoveryReviewed(false);
      setReloadedTarget(null);
      setTargetInvalid(false);
      setState(initialTextAssistanceState());
      latest.current.onPendingChange(false);
      latest.current.onRecoveryChange(false);
      latest.current.onClose();
    } catch (error) {
      if (current()) setFormError(humanError(error));
    } finally {
      if (resetFlight.current === flight) {
        resetFlight.current = null;
        if (current()) setInvalidResetBusy(false);
      }
    }
  }
  async function run(action: () => Promise<unknown> | unknown) {
    try {
      setFormError("");
      await action();
    } catch (error) {
      setFormError(humanError(error));
    }
  }
  const target = reloadedTarget ?? props.target;
  const recovery = state.recovery;
  const operation = recovery?.operation ?? target?.operation;
  const translating = operation === "translate";
  const proposal = canEdit && !authInvalid ? state.job?.proposal : null;
  const disabled = Boolean(state.busy) || invalidResetBusy || !canEdit || authInvalid;
  const unavailable =
    !status?.enabled || status.remaining === 0 || status.active >= status.maxActiveJobs;
  const availabilityFeedback = textAssistanceFeedback(locale, availabilityError);
  const errorFeedback = textAssistanceFeedback(locale, formError || state.error);
  const messageFeedback = textAssistanceFeedback(locale, state.message);
  const jobFeedback = textAssistanceFeedback(locale, state.job?.error?.message ?? "");
  if (!open) return null;
  return (
    <div
      className={styles.backdrop}
      role="dialog"
      aria-modal="true"
      aria-labelledby="text-assistance-title"
      tabIndex={-1}
      ref={dialog}
      onKeyDown={keyDown}
      lang={locale}
    >
      <section className={styles.dialog}>
        <div className={styles.heading}>
          <div>
            <p className={styles.eyebrow}>{copy("Optional AI assistance")}</p>
            <h2 id="text-assistance-title">
              {translating
                ? copy("Translate text")
                : operation === "shorten"
                  ? copy("Shorten text")
                  : copy("Rewrite text")}
            </h2>
          </div>
          <button type="button" onClick={props.onClose}>
            {copy("Close")}
          </button>
        </div>
        <p>
          {copy(
            "Only the selected saved plain text is sent to the configured provider. Review both complete versions before applying the proposed wording to this exact object.",
          )}
        </p>
        <p className={styles.help}>
          {copy(
            "Speaker notes, other objects and citation excerpts are not sent. Generation leaves the deck unchanged.",
          )}
        </p>
        <div role="status" aria-live="polite" className={styles.notice}>
          {!canEdit ? (
            copy("Editor permission is required.")
          ) : authInvalid ? (
            copy("Reload the editor after a sign-in change.")
          ) : status ? (
            <>
              <p>
                {status.monthlyLimit === null
                  ? copy("{used} AI jobs used this month; operator-configured allowance.", {
                      used: status.used,
                    })
                  : copy("{used} of {limit} AI jobs used this month ({remaining} remaining).", {
                      used: status.used,
                      limit: status.monthlyLimit,
                      remaining: status.remaining!,
                    })}{" "}
                {copy("One text proposal uses one job.")}
              </p>
              {!status.enabled ? (
                <p>{copy("AI assistance is disabled on this deployment.")}</p>
              ) : status.remaining === 0 ? (
                <p>
                  {copy(
                    "Your monthly AI allowance is used. Continue editing manually or return when your allowance resets.",
                  )}
                </p>
              ) : status.active >= status.maxActiveJobs ? (
                <p>
                  {copy(
                    "Two AI jobs are already active. Wait for a job to finish, then retry availability.",
                  )}
                </p>
              ) : null}
            </>
          ) : (
            copy("Checking AI availability and allowance…")
          )}
        </div>
        {availabilityError ? (
          <p role="alert" lang={availabilityFeedback.lang}>
            {availabilityFeedback.text}
          </p>
        ) : null}
        <button type="button" disabled={disabled} onClick={() => setAttempt((value) => value + 1)}>
          {copy("Retry availability")}
        </button>
        {formError || state.error ? (
          <p role="alert" className={styles.error} lang={errorFeedback.lang}>
            {errorFeedback.text}
          </p>
        ) : null}
        {state.message ? (
          <p role="status" className={styles.notice} lang={messageFeedback.lang}>
            {messageFeedback.text}
          </p>
        ) : null}
        {invalidRecovery ? (
          <section aria-label={copy("Unverifiable text recovery")} className={styles.warning}>
            <h3>{copy("Saved text recovery could not be verified")}</h3>
            <p>
              {copy(
                "A previous text request may already have changed the saved deck. Reload its current saved contents before clearing this invalid tab record. Other saved requests and local recovery copies are retained.",
              )}
            </p>
            <label className={styles.check}>
              <input
                type="checkbox"
                checked={invalidRecoveryReviewed}
                disabled={disabled}
                onChange={(event) => setInvalidRecoveryReviewed(event.target.checked)}
              />
              <span>
                {copy(
                  "I understand the saved request cannot be recovered and a text edit may already have been applied.",
                )}
              </span>
            </label>
            <button
              type="button"
              disabled={disabled || !invalidRecoveryReviewed}
              onClick={() => void resetInvalidRecovery()}
            >
              {invalidResetBusy
                ? copy("Reloading saved deck…")
                : copy("Reload saved deck and clear invalid recovery")}
            </button>
          </section>
        ) : null}
        {!invalidRecovery && !recovery && target && canEdit && !authInvalid ? (
          <>
            <h3>{copy("Selected original text")}</h3>
            <p
              className={styles.slideBody}
              lang={target.operation === "translate" ? (target.sourceLanguage ?? "") : ""}
            >
              {target.text}
            </p>
            {target.operation === "translate" ? (
              <div className={styles.form}>
                <label>
                  {copy("Target language")}
                  <select
                    value={targetLanguage}
                    required
                    disabled={disabled}
                    onChange={(event) => {
                      if (controller.current?.state().recovery) return;
                      const parsed = PresentationTextLanguageSchema.safeParse(event.target.value);
                      setTargetLanguage(parsed.success ? parsed.data : "");
                    }}
                  >
                    <option value="">{copy("Choose a language")}</option>
                    {PRESENTATION_TEXT_LANGUAGES.map((language) => (
                      <option
                        key={language.code}
                        value={language.code}
                        disabled={language.code === target.sourceLanguage}
                        lang={textAssistanceLanguageDisplay(language.code, locale).lang}
                      >
                        {textAssistanceLanguageDisplay(language.code, locale).text}
                      </option>
                    ))}
                  </select>
                </label>
                <p className={styles.help}>
                  {copy(
                    "Choose the language for this text object. Review meaning and terminology before applying; translation may need more room in its existing frame.",
                  )}
                </p>
              </div>
            ) : null}
            <button
              type="button"
              disabled={
                disabled ||
                unavailable ||
                (target.operation === "translate" &&
                  (!targetLanguage || targetLanguage === target.sourceLanguage))
              }
              onClick={() =>
                void run(() =>
                  controller.current?.generate(
                    target,
                    target.operation === "translate"
                      ? { targetLanguage: PresentationTextLanguageSchema.parse(targetLanguage) }
                      : undefined,
                  ),
                )
              }
            >
              {target.operation === "translate"
                ? copy("Generate translation proposal")
                : target.operation === "shorten"
                  ? copy("Generate shorter text proposal")
                  : copy("Generate rewrite proposal")}
            </button>
          </>
        ) : null}
        {recovery?.operation === "translate" && recovery.targetLanguage ? (
          <p>
            <strong>{copy("Target language:")}</strong>{" "}
            <LanguageName language={recovery.targetLanguage} locale={locale} />.{" "}
            {copy("This saved request keeps its original target language during recovery.")}
          </p>
        ) : null}
        {state.job ? (
          <p role="status">
            {state.job.status === "pending" ? (
              copy("Proposal queued.")
            ) : state.job.status === "processing" ? (
              copy("Preparing text for review…")
            ) : state.job.status === "ready" ? (
              copy("Ready for review.")
            ) : (
              <>
                {copy(state.job.status === "expired" ? "Proposal expired." : "Proposal failed.")}{" "}
                <span lang={jobFeedback.lang}>{jobFeedback.text}</span>
              </>
            )}
          </p>
        ) : null}
        {proposal ? (
          <>
            <TextAssistanceProposalReview
              locale={locale}
              proposal={proposal}
              citations={props.citations}
              reviewed={state.reviewed}
              disabled={disabled || state.pending}
              onReview={(value) => controller.current?.review(value)}
            />
            <button
              type="button"
              disabled={disabled || state.pending || !state.reviewed || !target || targetInvalid}
              onClick={() => void run(() => controller.current?.apply(target))}
            >
              {translating ? copy("Apply reviewed translation") : copy("Apply reviewed text")}
            </button>
          </>
        ) : null}
        {recovery ? (
          <div className={styles.actions}>
            {recovery.applyBody ? (
              <button
                type="button"
                disabled={disabled}
                onClick={() => void run(() => controller.current?.apply(null))}
              >
                {copy("Retry exact text application")}
              </button>
            ) : (
              <>
                <button
                  type="button"
                  disabled={disabled}
                  onClick={() => void run(() => controller.current?.retry())}
                >
                  {recovery.createUncertain
                    ? copy("Recover or retry saved request")
                    : copy("Refresh proposal")}
                </button>
                <button
                  type="button"
                  disabled={disabled || state.pending}
                  onClick={() =>
                    void run(async () => {
                      setTargetInvalid(true);
                      const reloaded = await props.onReloadTarget(recovery);
                      if (controller.current?.rebase(reloaded)) {
                        setReloadedTarget(reloaded);
                        setTargetInvalid(false);
                      }
                    })
                  }
                >
                  {copy("Reload exact target and review")}
                </button>
                <button
                  type="button"
                  disabled={disabled || state.pending}
                  onClick={() =>
                    void run(() => {
                      if (controller.current?.reset()) {
                        setReloadedTarget(null);
                        props.onClose();
                      }
                    })
                  }
                >
                  {copy("Discard proposal")}
                </button>
              </>
            )}
          </div>
        ) : null}
      </section>
    </div>
  );
}
