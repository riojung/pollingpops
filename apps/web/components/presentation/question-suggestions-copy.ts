type LocalKey = keyof typeof messages;
export type QuestionSuggestionsCopyKey =
  LocalKey | (typeof assistanceKeys)[number] | (typeof controlKeys)[number];
export const questionSuggestionsCopyKeys: readonly QuestionSuggestionsCopyKey[] = [
  ...assistanceKeys,
  ...controlKeys,
  ...(Object.keys(messages) as LocalKey[]),
];
export function questionSuggestionsCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  const sharedAssistance = assistanceCopy(locale);
  const sharedControls = nativeControlsCopy(locale);
  return (
    key: QuestionSuggestionsCopyKey,
    values: Record<string, string | number> = {},
  ): string => {
    const message = Object.hasOwn(messages, key)
      ? column < 0
        ? key
        : messages[key as LocalKey][column]!
      : key === "Slide title"
        ? sharedControls(key)
        : sharedAssistance(key as (typeof assistanceKeys)[number]);
    return message.replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token));
  };
}

