export type SourceWorkflowsCopyKey = keyof typeof messages | "Close";
export const sourceWorkflowsCopyKeys: readonly SourceWorkflowsCopyKey[] = [
  ...(Object.keys(messages) as (keyof typeof messages)[]),
  "Close",
];
export function sourceWorkflowsCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  return (key: SourceWorkflowsCopyKey): string =>
    key === "Close" ? assistanceCopy(locale)("Close") : column < 0 ? key : messages[key][column]!;
}

export function sourceWorkflowsFeedback(locale: SupportedLocale, raw: string) {
  return raw === "Save this Presentation before inserting source proposals."
    ? { text: sourceWorkflowsCopy(locale)(raw), lang: locale }
    : { text: raw, lang: "en-CA" as const };
}
