type LocalKey = keyof typeof messages;
export type TextAssistanceCopyKey =
  LocalKey | (typeof sharedKeys)[number] | (typeof editorKeys)[number];
export const textAssistanceCopyKeys: readonly TextAssistanceCopyKey[] = [
  ...sharedKeys,
  ...editorKeys,
  ...(Object.keys(messages) as LocalKey[]),
];
export function textAssistanceCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  const shared = assistanceCopy(locale);
  const editor = nativeEditorCopy(locale);
  return (key: TextAssistanceCopyKey, values: Record<string, string | number> = {}): string => {
    if (Object.hasOwn(messages, key)) {
      const source = column < 0 ? key : messages[key as LocalKey][column]!;
      return source.replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token));
    }
    if ((editorKeys as readonly string[]).includes(key))
      return editor(key as (typeof editorKeys)[number], values);
    return shared(key as (typeof sharedKeys)[number], values);
  };
}

