type LocalKey = keyof typeof messages;
export type VisualImportCopyKey = LocalKey | "Slide title" | "Import visual slides";
export const visualImportCopyKeys: readonly VisualImportCopyKey[] = [
  "Slide title",
  "Import visual slides",
  ...(Object.keys(messages) as LocalKey[]),
];
export function visualImportCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  const controls = nativeControlsCopy(locale);
  return (key: VisualImportCopyKey, values: Record<string, string | number> = {}): string => {
    const message =
      key === "Import visual slides"
        ? column < 0
          ? key
          : presentationCommandCopy(locale).importVisual
        : key === "Slide title"
          ? controls(key, values)
          : column < 0
            ? key
            : messages[key][column]!;
    return message.replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token));
  };
}

