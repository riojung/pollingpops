export function presentationStartCopy(locale: SupportedLocale = "en-CA"): PresentationStartCopy {
  return Object.fromEntries(
    Object.keys(english).map((key, index) => [key, translated[locale][index]]),
  ) as PresentationStartCopy;
}

export function localizedOutlineError(error: string, copy: PresentationStartCopy): string | null {
  for (const key of [
    "authChanged",
    "storageError",
    "recoveryError",
    "acknowledgementError",
  ] as const)
    if (error === english[key]) return copy[key];
  return null;
}
