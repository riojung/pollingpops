export const assignmentSetupCopyKeys = Object.keys(rows) as Array<keyof typeof rows>;
export function assignmentSetupCopy(locale: SupportedLocale) {
  const index = locales.indexOf(locale as (typeof locales)[number]);
  return (key: keyof typeof rows, values: Record<string, string | number> = {}) => {
    const template = index < 0 ? key : (rows[key][index] ?? key);
    return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
  };
}
