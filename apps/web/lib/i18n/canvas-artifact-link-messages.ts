export function canvasArtifactLinkCopy(locale: SupportedLocale) {
  return Object.fromEntries(
    Object.keys(english).map((key, index) => [key, translations[locale][index]]),
  ) as Record<keyof typeof english, string>;
}
type Prefixed = { [K in keyof typeof english as `canvas.artifactLinks.${K}`]: string };
export function canvasArtifactLinkMessages(locale: SupportedLocale): Prefixed {
  return Object.fromEntries(
    Object.entries(canvasArtifactLinkCopy(locale)).map(([key, value]) => [
      `canvas.artifactLinks.${key}`,
      value,
    ]),
  ) as Prefixed;
}
