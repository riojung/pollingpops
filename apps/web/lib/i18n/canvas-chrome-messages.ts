export function canvasChromeCopy(locale: SupportedLocale): CanvasChromeCopy {
  const values = translations[locale] ?? Object.values(english);
  return Object.fromEntries(
    Object.entries(english).map(([key, fallback], index) => [key, values[index] ?? fallback]),
  ) as CanvasChromeCopy;
}
