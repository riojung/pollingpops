export function canvasDiagramCopy(locale: SupportedLocale): CanvasDiagramCopy {
  return Object.fromEntries(
    Object.keys(english).map((key, index) => [key, translations[locale][index]]),
  ) as CanvasDiagramCopy;
}
type Prefixed = { [K in keyof typeof english as `canvas.diagram.${K}`]: string };
function prefixed(copy: CanvasDiagramCopy): Prefixed {
  return Object.fromEntries(
    Object.entries(copy).map(([key, value]) => [`canvas.diagram.${key}`, value]),
  ) as Prefixed;
}
export const canvasDiagramEnglishMessages = prefixed(english);
export const canvasDiagramMessages = (locale: SupportedLocale) =>
  prefixed(canvasDiagramCopy(locale));
