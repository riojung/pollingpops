export function canvasPresenterCopy(locale: SupportedLocale): Record<keyof typeof english, string> {
  const values = translations[locale];
  return Object.fromEntries(
    Object.keys(english).map((key, index) => [
      key,
      values[index] ?? Object.values(english)[index]!,
    ]),
  ) as Record<keyof typeof english, string>;
}
export function canvasPresenterMessages(
  locale: SupportedLocale,
): Record<`canvas.presenter.${keyof typeof english}`, string> {
  return Object.fromEntries(
    Object.entries(canvasPresenterCopy(locale)).map(([key, value]) => [
      `canvas.presenter.${key}`,
      value,
    ]),
  ) as Record<`canvas.presenter.${keyof typeof english}`, string>;
}
