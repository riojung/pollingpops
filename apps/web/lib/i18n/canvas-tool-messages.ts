type FlatCanvasToolCopy = UiCopy & Record<CanvasShapeLabel | CanvasToolColor, string>;
export type CanvasToolCopy = FlatCanvasToolCopy & { colors: Record<CanvasToolColor, string> };
export function canvasToolCopy(locale: SupportedLocale): CanvasToolCopy {
  const flat = Object.fromEntries([
    ...Object.keys(english).map((key, index) => [key, uiTranslations[locale][index]]),
    ...shapeKeys.map((key, index) => [key, shapeTranslations[locale][index]]),
    ...colorKeys.map((key, index) => [key, colorTranslations[locale][index]]),
  ]) as FlatCanvasToolCopy;
  return {
    ...flat,
    colors: Object.fromEntries(colorKeys.map((key) => [key, flat[key]])) as Record<
      CanvasToolColor,
      string
    >,
  };
}
type Prefixed = { [K in keyof FlatCanvasToolCopy as `canvas.tools.${K}`]: string };
export function canvasToolMessages(locale: SupportedLocale): Prefixed {
  return Object.fromEntries(
    Object.entries(canvasToolCopy(locale))
      .filter(([key]) => key !== "colors")
      .map(([key, value]) => [`canvas.tools.${key}`, value]),
  ) as Prefixed;
}
