export function competitionText(
  locale: SupportedLocale,
  key: CompetitionCopyKey,
  values: Record<string, string | number> = {},
) {
  return competitionCopies[locale][key].replace(/\{(\w+)\}/g, (token, name: string) =>
    values[name] === undefined ? token : String(values[name]),
  );
}

export function competitionPlace(locale: SupportedLocale, rank: number) {
  const value = new Intl.NumberFormat(locale).format(rank);
  switch (locale) {
    case "en-CA": {
      const category = new Intl.PluralRules(locale, { type: "ordinal" }).select(rank);
      return `${value}${({ one: "st", two: "nd", few: "rd" } as Record<string, string>)[category] ?? "th"}`;
    }
    case "fr-FR":
      return `${value}${rank === 1 ? "er" : "e"}`;
    case "de-DE":
      return `${value}.`;
    case "es-ES":
    case "it-IT":
    case "pt-PT":
      return `${value}.º`;
    case "ja-JP":
      return `${value}位`;
    case "ko-KR":
      return `${value}위`;
    case "zh-CN":
    case "zh-TW":
      return `第${value}名`;
  }
}
