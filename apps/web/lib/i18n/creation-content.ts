export function creationContent(locale: SupportedLocale = "en-CA") {
  const row = rows[locale];
  return (key: Key, number?: number): string => {
    const value = row[keys.indexOf(key)]!;
    return number === undefined ? value : value.replace("{number}", String(number));
  };
}

