export type CompanionCopySource = keyof typeof rows;
export const companionCopySources = Object.keys(rows) as CompanionCopySource[];

export function companionCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  return (source: CompanionCopySource, values: Record<string, string | number> = {}) => {
    const template = column < 0 ? source : (rows[source][column] ?? source);
    return template.replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token));
  };
}

export function companionMessages(locale: SupportedLocale): Record<CatalogKey, string> {
  const copy = companionCopy(locale);
  return Object.fromEntries(
    Object.entries(companionEnglishMessages)
      .filter(
        ([key]) =>
          key.startsWith("live.companion.") ||
          key === "live.presentationReport.sessionOnlyQuickCheck",
      )
      .map(([key, source]) => [key, copy(source as CatalogSource)]),
  ) as Record<CatalogKey, string>;
}

export function localizeCompanionError(locale: SupportedLocale, message: string) {
  const source = Object.hasOwn(rows, message)
    ? (message as CompanionCopySource)
    : ["Failed to fetch", "Load failed", "Network request failed"].includes(message)
      ? "Unable to connect. Check your connection and retry."
      : null;
  const request = /^Request failed \((\d{3})\)$/.exec(message);
  return {
    text: source
      ? companionCopy(locale)(source)
      : request
        ? companionCopy(locale)("Request failed ({status})", { status: request[1]! })
        : message,
    language: source || request ? locale : "en-CA",
    known: Boolean(source || request),
  };
}
