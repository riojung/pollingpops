export type FollowupCopyKey = keyof typeof rows;
export const followupCopyKeys = Object.keys(rows) as FollowupCopyKey[];

export function followupCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  return (key: FollowupCopyKey, values: Record<string, string | number> = {}) => {
    const template: string = column < 0 ? key : rows[key][column]!;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
  };
}

/** Exact known system messages only; never infer a translation from an error code or status. */
export function localizeFollowupMessage(locale: SupportedLocale, message: string) {
  const failedRequest = /^Request failed \((\d{3})\)\.$/.exec(message);
  if (failedRequest)
    return {
      text: followupCopy(locale)("Request failed ({status}).", { status: failedRequest[1]! }),
      language: locale,
      known: true,
    };
  const known = Object.hasOwn(rows, message);
  return {
    text: known ? followupCopy(locale)(message as FollowupCopyKey) : message,
    language: known ? locale : "en-CA",
    known,
  };
}
