export function homeOverviewCopy(locale: SupportedLocale = "en-CA"): HomeOverviewCopy {
  return Object.hasOwn(translations, locale) ? translations[locale] : english;
}

/** Formats a localized UI template once, leaving supplied values literal. */
export function formatHomeOverviewText(
  template: string,
  values: Readonly<Record<string, string | number>>,
): string {
  return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}
