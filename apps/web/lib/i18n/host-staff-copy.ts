export const hostStaffCopyKeys = Object.keys(rows) as HostStaffCopyKey[];

export function hostStaffCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  return (key: HostStaffCopyKey, values: Record<string, string | number> = {}) => {
    const template = locale === "en-CA" ? key : (rows[key][column] ?? key);
    return template.replace(/\{(\w+)\}/g, (token, name: string) =>
      values[name] === undefined ? token : String(values[name]),
    );
  };
}
