export function libraryDiscoveryCopy(locale: SupportedLocale = "en-CA"): LibraryDiscoveryCopy {
  return Object.hasOwn(translations, locale) ? translations[locale] : english;
}

export function formatLibraryDiscoveryText(text: string, values: Record<string, string | number>) {
  return text.replace(/\{(\w+)\}/g, (placeholder, key: string) =>
    Object.hasOwn(values, key) ? String(values[key]) : placeholder,
  );
}
