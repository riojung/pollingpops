export type LiveWordCloudCopyKey = keyof (typeof liveWordCloudCopies)["en-CA"];
export function liveWordCloudCopy(
  locale: SupportedLocale,
  key: LiveWordCloudCopyKey,
  values: Record<string, string | number> = {},
) {
  return Object.entries(values).reduce<string>(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    liveWordCloudCopies[locale][key],
  );
}
