type Placeholders<T extends string> = T extends `${string}{${infer Name}}${infer Rest}`
  ? Name | Placeholders<Rest>
  : never;
export function packExportCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  return <K extends PackExportCopyKey>(
    key: K,
    ...args: [Placeholders<K>] extends [never]
      ? [values?: Record<string, string | number>]
      : [values: Record<Placeholders<K>, string | number>]
  ) => {
    const template: string = column < 0 ? key : rows[key][column]!;
    const values: Record<string, string | number> = args[0] ?? {};
    return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
  };
}
