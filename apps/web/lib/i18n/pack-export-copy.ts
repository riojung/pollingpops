export const packExportCanonicalFindings = Object.entries(findingReasons).map(([code, values]) => ({
  code,
  reason: values[0],
}));
export function packExportFindingReason(
  locale: SupportedLocale,
  finding: Pick<RecoveryPackExportFinding, "code" | "reason">,
) {
  const candidate = Object.hasOwn(findingReasons, finding.code)
    ? findingReasons[finding.code as keyof typeof findingReasons]
    : undefined;
  const known = candidate?.[0] === finding.reason;
  const column = locales.indexOf(locale as (typeof locales)[number]);
  return {
    text: known ? candidate![column + 1]! : finding.reason,
    lang: known ? locale : "en-CA",
    known,
  };
}
