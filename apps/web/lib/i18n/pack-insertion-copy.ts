export type PackInsertionCopyKey = keyof typeof rows | PackUpdateCopyKey | "Cancel";
export const packInsertionCopyKeys = Object.keys(rows) as (keyof typeof rows)[];
export function packInsertionCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  return (key: PackInsertionCopyKey, values: Record<string, string | number> = {}) => {
    if (key === "Cancel") return canvasFacilitationCopy(locale).cancel;
    if (!Object.hasOwn(rows, key)) return packUpdateCopy(locale)(key as PackUpdateCopyKey, values);
    const template: string = column < 0 ? key : rows[key as keyof typeof rows][column]!;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
  };
}
const feedbackKeys = new Set<string>([
  "Save the latest Presentation changes before inserting a Pack.",
  "Your local changes were preserved. Reload the current draft after preserving a local copy.",
]);
export function packInsertionFeedback(
  locale: SupportedLocale,
  message: string,
): { text: string; lang: string } {
  return feedbackKeys.has(message)
    ? { text: packInsertionCopy(locale)(message as keyof typeof rows), lang: locale }
    : packUpdateFeedback(locale, message, "Presentation");
}
