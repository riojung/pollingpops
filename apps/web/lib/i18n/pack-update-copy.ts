/** Exact, allowlisted system feedback only. Unknown diagnostics retain their original bytes. */
export function packUpdateFeedback(
  locale: SupportedLocale,
  message: string,
  artifactLabel: "Round" | "Presentation" = "Round",
): { text: string; lang: string } {
  const copy = packUpdateCopy(locale);
  for (const artifact of ["Round", "Presentation"] as const) {
    for (const key of [
      "Finish saving or reload this {artifact} before reviewing a Pack update.",
      "Reload the saved {artifact} before reviewing a Pack update.",
    ] as const) {
      if (message === key.replace("{artifact}", artifact))
        return { text: copy(key, { artifact: copy(artifact) }), lang: locale };
    }
    const artifacts = artifact === "Round" ? "Rounds" : "Presentations";
    const key =
      "Pack update saved as one draft revision. Published {artifacts} and the original inserted baseline are unchanged.";
    if (message === key.replace("{artifacts}", artifacts))
      return { text: copy(key, { artifacts: copy(artifacts) }), lang: locale };
  }
  const linkTemplates = [
    "Choose the latest published diagnostic too, or repair its recheck link in the {artifact} and review again. Keeping the unlinked local diagnostic would orphan the restored recheck.",
    "Choose the latest published recheck too, or repair its delivery in the {artifact} and review again. The diagnostic must link to a recheck checkpoint.",
  ] as const;
  for (const key of linkTemplates) {
    if (
      message === key.replace("{artifact}", "Round") ||
      message === key.replace("{artifact}", "Presentation")
    )
      return { text: copy(key, { artifact: copy(artifactLabel) }), lang: locale };
  }
  return feedbackKeySet.has(message)
    ? { text: copy(message as PackUpdateCopyKey), lang: locale }
    : { text: message, lang: "en-CA" };
}
