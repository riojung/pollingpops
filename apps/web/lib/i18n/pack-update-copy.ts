export type PackUpdateCopyKey = keyof typeof rows;
export const packUpdateCopyKeys = Object.keys(rows) as PackUpdateCopyKey[];
export function packUpdateCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  return (key: PackUpdateCopyKey, values: Record<string, string | number> = {}) => {
    const template: string = column < 0 ? key : rows[key][column]!;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
  };
}
