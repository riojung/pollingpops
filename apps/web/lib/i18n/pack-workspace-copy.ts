export type PackWorkspaceCopyKey = keyof typeof rows;
export const packWorkspaceCopyKeys = Object.keys(rows) as PackWorkspaceCopyKey[];

export function packWorkspaceCopy(locale: SupportedLocale = "en-CA") {
  return (key: PackWorkspaceCopyKey, values: Record<string, string | number> = {}): string => {
    const index = locales.indexOf(locale as (typeof locales)[number]);
    const template = index < 0 ? key : (rows[key][index] ?? key);
    return template.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
      Object.hasOwn(values, name) ? String(values[name]) : placeholder,
    );
  };
}

