/** Exact system-message allowlist. Unknown diagnostics stay verbatim in English. */
export function packWorkspaceFeedback(
  locale: SupportedLocale,
  raw: string,
): { text: string; lang: SupportedLocale } {
  if (knownFeedback.has(raw))
    return { text: packWorkspaceCopy(locale)(raw as PackWorkspaceCopyKey), lang: locale };
  const history = /^Loaded (\d+) draft revisions\.$/.exec(raw);
  if (history)
    return {
      text: packWorkspaceCopy(locale)("Loaded {count} draft revisions.", { count: history[1]! }),
      lang: locale,
    };
  return { text: raw, lang: "en-CA" };
}
