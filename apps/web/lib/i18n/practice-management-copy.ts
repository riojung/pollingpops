export type PracticeManagementCopyKey = keyof typeof rows | (typeof sharedKeys)[number];
export const practiceManagementCopyKeys = [
  ...Object.keys(rows),
  ...sharedKeys,
] as PracticeManagementCopyKey[];
export function practiceManagementCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  return (key: PracticeManagementCopyKey, values: Record<string, string | number> = {}) => {
    if ((sharedKeys as readonly string[]).includes(key))
      return followupCopy(locale)(key as (typeof sharedKeys)[number], values);
    const template: string = column < 0 ? key : rows[key as keyof typeof rows][column]!;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
  };
}
