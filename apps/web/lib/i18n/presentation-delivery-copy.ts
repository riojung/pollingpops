export function presentationDeliveryCopy(locale: SupportedLocale = "en-CA") {
  const messages: PresentationDeliveryCopy = locale === "en-CA" ? english : translations[locale];
  return (key: PresentationDeliveryCopyKey, values: Record<string, string | number> = {}) =>
    messages[key].replace(/\{(\w+)\}/g, (token, name: string) =>
      values[name] === undefined ? token : String(values[name]),
    );
}

