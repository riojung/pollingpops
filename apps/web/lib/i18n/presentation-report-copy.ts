/** Localizes known report UI copy and interpolates once, leaving supplied values literal. */
export function presentationReportCopy(locale: SupportedLocale = "en-CA") {
  const copy = Object.hasOwn(translations, locale) ? translations[locale] : english;
  return (key: PresentationReportCopyKey, values: Record<string, string | number> = {}): string =>
    copy[key].replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}
