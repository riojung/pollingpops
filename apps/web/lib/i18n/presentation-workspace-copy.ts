export type PresentationWorkspaceCopyKey = keyof typeof messages;
export const presentationWorkspaceCopyKeys = Object.keys(
  messages,
) as PresentationWorkspaceCopyKey[];

/** Display copy only; values are supplied by the caller and interpolated once, literally. */
export function presentationWorkspaceCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  return (
    phrase: PresentationWorkspaceCopyKey,
    values: Record<string, string | number> = {},
  ): string => {
    const template: string = column < 0 ? phrase : messages[phrase][column]!;
    return template.replace(/\{(\w+)\}/g, (token, name: string) =>
      Object.hasOwn(values, name) ? String(values[name]) : token,
    );
  };
}
