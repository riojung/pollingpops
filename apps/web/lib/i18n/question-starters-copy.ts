type RowKey = keyof typeof rows;
export type QuestionStartersCopyKey = RowKey | "Close" | "Cancel";
export const questionStartersCopyKeys = [
  ...Object.keys(rows),
  "Close",
  "Cancel",
] as QuestionStartersCopyKey[];
type Placeholders<T extends string> = T extends `${string}{${infer Name}}${infer Rest}`
  ? Name | Placeholders<Rest>
  : never;

export function questionStartersCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  return <K extends QuestionStartersCopyKey>(
    key: K,
    ...args: [Placeholders<K>] extends [never]
      ? [values?: Record<string, string | number>]
      : [values: Record<Placeholders<K>, string | number>]
  ) => {
    const shared = key === "Close" || key === "Cancel" ? canvasFacilitationCopy(locale) : null;
    const template: string =
      key === "Close"
        ? shared!.close
        : key === "Cancel"
          ? shared!.cancel
          : column < 0
            ? key
            : rows[key as RowKey][column]!;
    const values: Record<string, string | number> = args[0] ?? {};
    return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
  };
}

