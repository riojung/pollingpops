export type RoundNavigationMessage = keyof typeof roundNavigationMessages;

export function roundNavigationCopy(locale: SupportedLocale = "en-CA") {
  const index = translationLocales.findIndex((candidate) => candidate === locale);
  return (source: RoundNavigationMessage, values: Record<string, string | number> = {}): string => {
    const translated = index < 0 ? source : (roundNavigationMessages[source][index] ?? source);
    return translated.replace(/\{(\w+)\}/g, (placeholder, key: string) =>
      values[key] === undefined ? placeholder : String(values[key]),
    );
  };
}
