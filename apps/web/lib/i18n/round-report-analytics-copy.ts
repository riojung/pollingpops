const singularResponseCounts: Partial<Record<SupportedLocale, string>> = {
  "en-CA": "{count} response",
  "fr-FR": "{count} réponse",
  "de-DE": "{count} Antwort",
  "es-ES": "{count} respuesta",
  "it-IT": "{count} risposta",
  "pt-PT": "{count} resposta",
};

export function roundReportAnalyticsCopy(locale: SupportedLocale = "en-CA") {
  const language = Object.hasOwn(translations, locale) ? locale : "en-CA";
  const messages = translations[language];
  return (key: RoundReportAnalyticsCopyKey, values: Record<string, string | number> = {}) => {
    const count = values.count;
    const template =
      key === "responseCount" &&
      typeof count === "number" &&
      pluralCategory(language, count) === "one"
        ? (singularResponseCounts[language] ?? messages[key])
        : messages[key];
    return template.replace(/\{(\w+)\}/g, (token, name: string) => {
      if (!Object.hasOwn(values, name)) return token;
      const value = values[name];
      return typeof value === "number" ? formatNumber(language, value) : (value ?? token);
    });
  };
}
