export function sidebarMessages(locale: SupportedLocale) {
  const keys = Object.keys(english) as Array<keyof typeof english>;
  if (copy[locale].length !== keys.length) throw new Error(`Incomplete sidebar copy: ${locale}`);
  return Object.fromEntries(keys.map((key, index) => [key, copy[locale][index]])) as Record<
    keyof typeof english,
    string
  >;
}
