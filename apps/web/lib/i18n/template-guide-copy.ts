export type TemplateGuideCopyKey = keyof typeof rows;
export const templateGuideCopyKeys = Object.keys(rows) as TemplateGuideCopyKey[];

export function templateGuideCopy(locale: SupportedLocale = "en-CA") {
  const column = locales.indexOf(locale as (typeof locales)[number]);
  return (key: TemplateGuideCopyKey, values: Record<string, string | number> = {}): string => {
    const template: string = column < 0 ? key : rows[key][column]!;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
  };
}
